package flamingo.aprendendo.basico;

public class OperadoresParte06 {
    public static void main (String[] args) {

        int contador = 0;

        contador = contador + 1;
        contador += 1;
        contador ++;

        contador = contador -1;
        contador -= 1;
        contador --;


        System.out.println(contador);


    }

}
