package flamingo.aprendendo.basico;

public class OperadoresParte02 {
    public static void main(String[] args) {
        /*
        *  < menor que
        *  > maior que
        *  <= menor ou igual
        *  >= maior ou igual
        *  == igual a
        *  != diferente de
        */

        int a = 10;
        int b = 12;

        System.out.println(a < b);
        System.out.println(a > b);
        System.out.println(a <= b);
        System.out.println(a >= b);
        System.out.println(a == b);
        System.out.println(a != b);
    }
}
